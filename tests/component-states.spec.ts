import {capture} from './screenshot';
import { expect, test } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test('primary action, tooltip, disabled export, and busy feedback have reviewable states', async ({ page, request }) => {
  await mkdir('artifacts/ui-after/states', { recursive: true });
  await request.post('/api/stop');
  await page.goto('/dashboard');
  const start = page.getByRole('button', { name: 'Start replay', exact: true });
  await expect(start).toBeEnabled();
  const durations = await start.evaluate(node => getComputedStyle(node).transitionDuration.split(',').map(value => Number.parseFloat(value)));
  expect(durations.length).toBeGreaterThan(0);
  expect(durations.every(seconds => seconds >= 0.12 && seconds <= 0.2)).toBeTruthy();
  await expect(page.getByRole('button', { name: /End stream/ })).toBeDisabled();
  await capture(page,{ path: 'artifacts/ui-after/states/component-default-disabled.png', fullPage: true, animations: 'disabled' });
  await start.hover();
  await capture(page,{ path: 'artifacts/ui-after/states/component-hover.png', fullPage: true, animations: 'disabled' });
  await start.focus();
  await capture(page,{ path: 'artifacts/ui-after/states/component-focus.png', fullPage: true, animations: 'disabled' });
  const box = await start.boundingBox();
  expect(box).toBeTruthy();
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2);
  await page.mouse.down();
  await capture(page,{ path: 'artifacts/ui-after/states/component-active.png', fullPage: true, animations: 'disabled' });
  let release = () => {};
  const hold = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/replay', async route => { await hold; await route.continue(); });
  await page.mouse.up();
  await expect(start).toHaveAttribute('aria-busy', 'true');
  await expect(start).toBeDisabled();
  await capture(page,{ path: 'artifacts/ui-after/states/component-loading.png', fullPage: true, animations: 'disabled' });
  release();
  await expect(page.getByTestId('approval-queue').locator('.queue-card').first()).toBeVisible();
  const copy = page.getByRole('button', { name: 'Copy overlay URL', exact: true });
  await copy.hover();
  await expect(page.getByRole('tooltip')).toBeVisible();
  await capture(page,{ path: 'artifacts/ui-after/states/component-tooltip.png', fullPage: true, animations: 'disabled' });
  await copy.click();
  await expect(page.locator('.toast')).toBeVisible();
  await capture(page,{ path: 'artifacts/ui-after/states/component-copy-toast.png', fullPage: true, animations: 'disabled' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const reduced = await page.locator('.button').first().evaluate(node => Number.parseFloat(getComputedStyle(node).transitionDuration));
  expect(reduced).toBeLessThanOrEqual(0.001);
});
